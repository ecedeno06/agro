SET client_encoding = 'UTF8';

BEGIN;

DROP VIEW  IF EXISTS v_ocupacion;
DROP TABLE IF EXISTS ocupacion;
DROP TABLE IF EXISTS categoria_ocupacion;

CREATE TABLE categoria_ocupacion (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(10)  NOT NULL UNIQUE,
    nombre_es VARCHAR(100) NOT NULL,
    nombre_en VARCHAR(100) NOT NULL,
    orden     SMALLINT     NOT NULL DEFAULT 0,
    activo    BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE ocupacion (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  INTEGER      NOT NULL,
    codigo        VARCHAR(20)  NOT NULL UNIQUE,
    nombre_es     VARCHAR(120) NOT NULL,
    nombre_en     VARCHAR(120) NOT NULL,
    codigo_ciuo   CHAR(4),
    requiere_detalle BOOLEAN   NOT NULL DEFAULT FALSE,  -- TRUE = pedir texto libre (ej. "Otro")
    orden         SMALLINT     NOT NULL DEFAULT 0,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_ocupacion_categoria FOREIGN KEY (categoria_id)
        REFERENCES categoria_ocupacion(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX ix_ocupacion_categoria ON ocupacion(categoria_id);
CREATE INDEX ix_ocupacion_nombre_es ON ocupacion(nombre_es);
CREATE INDEX ix_ocupacion_nombre_en ON ocupacion(nombre_en);

COMMENT ON TABLE  categoria_ocupacion IS 'Agrupación de ocupaciones del sector agro';
COMMENT ON TABLE  ocupacion IS 'Ocupaciones que puede seleccionar un usuario del sistema agro';
COMMENT ON COLUMN ocupacion.codigo_ciuo IS 'Grupo unitario CIUO-08 / ISCO-08 (OIT)';
COMMENT ON COLUMN ocupacion.requiere_detalle IS 'Si es TRUE, la interfaz debe pedir una descripción libre';

