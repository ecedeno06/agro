-- ---------------- VISTA PARA LA APP ----------------
-- Devuelve la lista lista para un selector agrupado, en ambos idiomas.
CREATE VIEW v_ocupacion AS
SELECT o.id,
       o.codigo,
       o.nombre_es,
       o.nombre_en,
       o.codigo_ciuo,
       o.requiere_detalle,
       c.codigo    AS categoria_codigo,
       c.nombre_es AS categoria_es,
       c.nombre_en AS categoria_en,
       c.orden     AS categoria_orden,
       o.orden
FROM ocupacion o
JOIN categoria_ocupacion c ON c.id = o.categoria_id
WHERE o.activo AND c.activo;

